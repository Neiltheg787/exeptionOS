export const defaultScenarioId = "supplier-loop";

export function getScenario(scenarioId?: string | null): DemoScenario {
  return demoScenarios.find((scenario) => scenario.id === scenarioId) ?? demoScenarios[0]!;
}

export function isScenarioId(value: string | null | undefined): value is string {
  return Boolean(value && demoScenarios.some((scenario) => scenario.id === value));
}
